"""profile, validate, and visualize a text dataset on real data.

usage:
    python scripts/analyze_dataset.py                                  # datasets/train_essays.csv
    python scripts/analyze_dataset.py --csv path.csv \\
        --text-col text --label-col generated

writes a json profile, a json validation report, a human-readable markdown summary, and
report-ready figures to reports/dataset. the work lives in ml-core; this script only
orchestrates and formats, so the same analysis runs from anywhere.
"""

from __future__ import annotations

# ruff: noqa: E402  — ml-core lives on a sibling path that must be added before importing it.

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "packages" / "ml-core"))

from ml_core.analytics import top_tokens
from ml_core.dataset import (
    TextDatasetSchema,
    load_dataset,
    profile_dataset,
    validate_dataset,
)
from ml_core.preprocessing.stopwords import ENGLISH_STOPWORDS
from ml_core.visualization import (
    plot_class_distribution,
    plot_text_length_distribution,
    plot_top_tokens,
    save_figure,
)

OUT = ROOT / "reports" / "dataset"


def _markdown_summary(profile, report, version: str) -> str:
    cd = profile.class_distribution
    lines = [
        f"# Dataset analysis — {version}",
        "",
        "Generated by `scripts/analyze_dataset.py`. All figures live alongside this file in",
        "`reports/dataset/` and are reused in the report.",
        "",
        "## Overview",
        "",
        f"- Samples: **{profile.total_samples}**",
        f"- Columns: {profile.n_columns}",
        f"- Valid: **{report.is_valid}** ({len(report.errors)} errors, {len(report.warnings)} warnings)",
        "",
        "## Text length",
        "",
        "| unit | mean | median | min | max | stdev |",
        "| --- | --- | --- | --- | --- | --- |",
        f"| characters | {profile.char_length.mean:.0f} | {profile.char_length.median:.0f} | "
        f"{profile.char_length.minimum} | {profile.char_length.maximum} | {profile.char_length.stdev:.0f} |",
        f"| words | {profile.word_length.mean:.0f} | {profile.word_length.median:.0f} | "
        f"{profile.word_length.minimum} | {profile.word_length.maximum} | {profile.word_length.stdev:.0f} |",
        "",
        "## Vocabulary",
        "",
        f"- Unique tokens: {profile.vocabulary.size:,}",
        f"- Total tokens: {profile.vocabulary.total_tokens:,}",
        f"- Type/token ratio: {profile.vocabulary.type_token_ratio:.4f}",
        "",
    ]

    if cd is not None:
        lines += ["## Class distribution", ""]
        lines += ["| class | count | proportion |", "| --- | --- | --- |"]
        for label, count in sorted(cd.counts.items()):
            lines.append(f"| {label} | {count} | {cd.proportions[label]:.4f} |")
        lines += [
            "",
            f"- Classes: {cd.n_classes}",
            f"- Imbalance ratio (largest/smallest): **{cd.imbalance_ratio:.1f}**",
            "",
        ]

    if report.issues:
        lines += ["## Validation findings", ""]
        for issue in report.issues:
            lines.append(f"- **{issue.severity}** `{issue.code}`: {issue.message} ({issue.count})")
        lines.append("")

    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--csv", default=str(ROOT / "datasets" / "train_essays.csv"))
    parser.add_argument("--text-col", default="text")
    parser.add_argument("--label-col", default="generated")
    parser.add_argument("--top-n", type=int, default=25)
    args = parser.parse_args()

    version = Path(args.csv).stem
    schema = TextDatasetSchema(text_column=args.text_col, label_column=args.label_col)
    dataset = load_dataset(args.csv, schema)

    profile = profile_dataset(dataset)
    report = validate_dataset(dataset)

    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "dataset_profile.json").write_text(json.dumps(profile.to_dict(), indent=2))
    (OUT / "validation_report.json").write_text(json.dumps(report.to_dict(), indent=2))
    (OUT / "summary.md").write_text(_markdown_summary(profile, report, version))

    # figures: class balance, length histograms, and word frequency overall + per class.
    if profile.class_distribution is not None:
        save_figure(plot_class_distribution(profile.class_distribution), OUT / "class_distribution.png")

    from ml_core.analytics import text_lengths

    save_figure(
        plot_text_length_distribution(text_lengths(dataset.texts, "word"), unit="word"),
        OUT / "word_length_distribution.png",
    )
    save_figure(
        plot_text_length_distribution(text_lengths(dataset.texts, "char"), unit="char"),
        OUT / "char_length_distribution.png",
    )

    overall = top_tokens(dataset.texts, top_n=args.top_n, stopwords=ENGLISH_STOPWORDS)
    save_figure(plot_top_tokens(overall, title="most frequent tokens (stopwords removed)"), OUT / "top_tokens.png")

    # per-class word frequency for class comparison, when labels and both classes exist.
    labels = dataset.labels
    if labels is not None:
        by_class: dict[str, list[str]] = {}
        for text, label in zip(dataset.texts, labels):
            by_class.setdefault(str(label), []).append(text)
        for label, texts in sorted(by_class.items()):
            freqs = top_tokens(texts, top_n=args.top_n, stopwords=ENGLISH_STOPWORDS)
            save_figure(
                plot_top_tokens(freqs, title=f"most frequent tokens — class {label} (n={len(texts)})"),
                OUT / f"top_tokens_class_{label}.png",
            )

    print(f"dataset analysis — {version}: {profile.total_samples} samples")
    print(f"  valid={report.is_valid}  warnings={len(report.warnings)}  errors={len(report.errors)}")
    if profile.class_distribution is not None:
        print(f"  classes={profile.class_distribution.counts}  imbalance={profile.class_distribution.imbalance_ratio:.1f}")
    print(f"  outputs: {OUT}")


if __name__ == "__main__":
    main()
